// UICert describes the certificate this web page is serving, for the Settings page.
type UICert struct {
	// TLS is false when CertSmith serves plain HTTP behind a reverse proxy: the proxy owns the certificate.
	TLS         bool      `json:"tls"`
	SelfSigned  bool      `json:"self_signed"`
	Bootstrap   bool      `json:"bootstrap"` // the self-signed certificate CertSmith created itself
	Subject     string    `json:"subject,omitempty"`
	Issuer      string    `json:"issuer,omitempty"`
	Names       []string  `json:"names,omitempty"`
	NotBefore   time.Time `json:"not_before,omitzero"`
	NotAfter    time.Time `json:"not_after,omitzero"`
	Fingerprint string    `json:"fingerprint,omitempty"` // SHA-256 of the certificate, hex
	// MissingNames are names of this machine (host name, IPv4 addresses) that CertSmith's own
	// certificate does not cover, because they changed after it was made.
	MissingNames []string `json:"missing_names,omitempty"`
	Error        string   `json:"error,omitempty"`
}

func commonOrOrg(n interface{ String() string }, cn string, org []string) string {
	switch {
	case cn != "":
		return cn
	case len(org) > 0:
		return org[0]
	}
	return n.String()
}

// uiCertInfo reads the certificate file the page is served from.
func uiCertInfo() UICert {
	dir := plugin.GetOptions().UITLSDir
	if dir == "" {
		return UICert{}
	}
	out := UICert{TLS: true}
	b, err := os.ReadFile(filepath.Join(dir, uitls.CertFile))
	if err != nil {
		out.Error = err.Error()
		return out
	}
	blk, _ := pem.Decode(b)
	if blk == nil {
		out.Error = "no certificate in " + uitls.CertFile
		return out
	}
	c, err := x509.ParseCertificate(blk.Bytes)
	if err != nil {
		out.Error = err.Error()
		return out
	}
	sum := sha256.Sum256(c.Raw)
	out.Fingerprint = hex.EncodeToString(sum[:])
	out.SelfSigned = bytes.Equal(c.RawIssuer, c.RawSubject)
	out.Bootstrap = uitls.IsBootstrap(c)
	if out.Bootstrap {
		out.MissingNames = uitls.Missing(c)
	}
	out.Subject = commonOrOrg(c.Subject, c.Subject.CommonName, c.Subject.Organization)
	out.Issuer = commonOrOrg(c.Issuer, c.Issuer.CommonName, c.Issuer.Organization)
	out.Names = append(out.Names, c.DNSNames...)
	for _, ip := range c.IPAddresses {
		out.Names = append(out.Names, ip.String())
	}
	out.NotBefore, out.NotAfter = c.NotBefore, c.NotAfter
	return out
}

// shortFingerprint is the first bytes of a fingerprint, colon separated, for audit entries and messages.
func shortFingerprint(hexSum string) string {
	var parts []string
	for i := 0; i+2 <= len(hexSum) && i < 16; i += 2 {
		parts = append(parts, strings.ToUpper(hexSum[i:i+2]))
	}
	return strings.Join(parts, ":")
}

// regenerateUICert makes a new self-signed certificate for this page. Only the certificate CertSmith made
// for itself can be replaced this way, and the person confirms with their password: a reverse proxy that
// pins the old fingerprint refuses the new certificate until it is updated.
func (s *Server) regenerateUICert(w http.ResponseWriter, r *http.Request) {
	var in struct{ Confirm string }
	if !decode(w, r, &in) {
		return
	}
	me, ok := s.confirmSelf(w, r, in.Confirm)
	if !ok {
		return
	}
	dir := plugin.GetOptions().UITLSDir
	if dir == "" {
		fail(w, http.StatusBadRequest, "this page is served without TLS (a reverse proxy provides HTTPS), so there is no certificate to regenerate")
		return
	}
	cur := uiCertInfo()
	switch {
	case cur.Error != "":
		fail(w, http.StatusInternalServerError, "the current certificate could not be read: "+cur.Error)
		return
	case !cur.Bootstrap:
		fail(w, http.StatusConflict, "this page uses a certificate that CertSmith did not create for itself, so it is not replaced here: change it from the target that manages it")
		return
	}
	if err := uitls.Regenerate(dir); err != nil {
		fail(w, http.StatusInternalServerError, "could not write the new certificate: "+err.Error())
		return
	}
	now := uiCertInfo()
	s.auditAs(r, me.Name, "ui_cert.regenerate", "web interface", "new SHA-256 "+shortFingerprint(now.Fingerprint)+"...")
	s.St.AddEvent("info", "web interface", "self-signed certificate regenerated by "+me.Name)
	s.notifyAdmin(notify.UICertRenewed, "[CertSmith] web page certificate regenerated",
		me.Name+" regenerated the self-signed certificate of the CertSmith web page. New SHA-256 fingerprint: "+now.Fingerprint+
			". A reverse proxy that pins the previous fingerprint must be updated.")
	writeJSON(w, map[string]any{"ok": true, "ui_cert": now})
}

// uiCertRenewWithin is how long before expiry CertSmith replaces its own certificate.
const uiCertRenewWithin = 30 * 24 * time.Hour

// AutoRenewUICert renews the page's self-signed certificate shortly before it expires. Nobody manages
// that certificate, so without this it would simply lapse. It returns when ctx ends.
func (s *Server) AutoRenewUICert(ctx context.Context) {
	timer := time.NewTimer(2 * time.Minute)
	defer timer.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-timer.C:
		}
		s.renewUICertOnce(time.Now(), uiCertRenewWithin)
		timer.Reset(6 * time.Hour)
	}
}

// renewUICertOnce renews the certificate if it is CertSmith's own and due. It reports whether it did.
func (s *Server) renewUICertOnce(now time.Time, within time.Duration) bool {
	dir := plugin.GetOptions().UITLSDir
	if dir == "" {
		return false
	}
	renewed, err := uitls.RenewIfDue(dir, within, now)
	if err != nil {
		s.Log.Warn("could not check the web page certificate for renewal", "err", err)
		return false
	}
	if !renewed {
		return false
	}
	info := uiCertInfo()
	s.Log.Info("renewed the self-signed certificate of the web page", "sha256", info.Fingerprint)
	s.St.AddEvent("info", "web interface", "renewed its self-signed certificate before it expired")
	s.St.AddAudit(model.AuditEntry{Time: now, Action: "ui_cert.renew", Subject: "web interface",
		Detail: "new SHA-256 " + shortFingerprint(info.Fingerprint) + "..."})
	s.notifyAdmin(notify.UICertRenewed, "[CertSmith] web page certificate renewed",
		"The self-signed certificate of the CertSmith web page was close to expiry and has been renewed. New SHA-256 fingerprint: "+
			info.Fingerprint+". A reverse proxy that pins the previous fingerprint must be updated.")
	return true
}
